export function getDepartmentById(id: number) {
  return departments.find((d) => d.id === id) || null;
}

export function getDoctorServices(doctorId: number) {
  const doc = doctors.find((d) => d.id === doctorId);
  if (!doc) return [];
  return services.filter((s) => s.doctorId === doctorId || (s.departmentId === doc.departmentId && !s.doctorId));
}
